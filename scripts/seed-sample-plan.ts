export const PROTECTED_EMAILS = [
	"staff@hmongtea.com",
	"customer@hmongtea.com",
	"partner@hmongtea.com",
] as const;

export const SAMPLE_EMAIL_PATTERN = /^sample-.*@example\.com$/;
export const SAMPLE_ID_PREFIX = "c0870000-";

export function isSampleEmail(email: string): boolean {
	return SAMPLE_EMAIL_PATTERN.test(email.toLowerCase());
}

export function isProtectedEmail(email: string): boolean {
	return (PROTECTED_EMAILS as readonly string[]).includes(email.toLowerCase());
}

export function daysAgo(days: number, hour = 16, minute = 0): Date {
	const date = new Date();
	date.setUTCDate(date.getUTCDate() - days);
	date.setUTCHours(hour, minute, 0, 0);
	return date;
}

export function isoDate(date: Date): string {
	return date.toISOString().slice(0, 10);
}

export function sampleId(kind: string, n: number): string {
	return `c0870000-${kind}-4000-8000-${String(n).padStart(12, "0")}`;
}

